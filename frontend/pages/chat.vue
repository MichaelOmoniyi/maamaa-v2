<template>
  <div class="w-full h-full flex flex-col">
    <!-- Welcome screen (shown when no chat is active) -->
    <div v-if="!currentChat" class="flex-1 flex flex-col items-center justify-center px-4">
      <h1 class="text-4xl font-bold text-gray-800 mb-2">Welcome, {{ userName }}</h1>
      
      <div class="w-full max-w-2xl mt-8">
        <div class="relative">
          <input 
            v-model="newChatMessage" 
            type="text" 
            placeholder="Write a note for your catering plan"
            class="w-full px-4 py-4 pr-12 border border-gray-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-green-500"
            :disabled="sendingMessage"
            @keyup.enter="sendNewMessage"
          />
          <button 
            @click="sendNewMessage" 
            :disabled="sendingMessage"
            class="absolute right-2 top-1/2 transform -translate-y-1/2 p-2 bg-green-600 text-white rounded-full hover:bg-green-700"
          >
            <svg class="w-5 h-5" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
              <path d="M5 12H19M19 12L12 5M19 12L12 19" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>
            </svg>
          </button>
        </div>
        <p class="mt-2 text-sm text-gray-500" role="note">
          Recent chat text is sent to Google Gemini. Google may use data submitted on its free tier to improve its products. Do not include passwords, payment details, or sensitive information.
        </p>
      </div>
      
      <!-- Quick suggestion buttons -->
      <div class="flex flex-wrap justify-center gap-4 mt-6">
        <button 
          v-for="(suggestion, index) in suggestions" 
          :key="index"
          @click="startChatWithSuggestion(suggestion)"
          class="px-4 py-3 bg-gray-100 hover:bg-gray-200 rounded-lg text-gray-700 text-sm font-medium transition-colors"
        >
          {{ suggestion }}
        </button>
      </div>

      <!-- Free plan info -->
      <div class="mt-6 bg-gray-50 rounded-lg px-4 py-2 flex items-center gap-2">
        <span class="text-sm text-gray-600">Free plan</span>
        <span class="w-1.5 h-1.5 bg-green-500 rounded-full"></span>
        <a href="#" class="text-sm font-medium text-green-700">Upgrade</a>
      </div>
    </div>
    
    <!-- Chat conversation (shown when a chat is active) -->
    <div v-else class="flex flex-col h-full">
      <!-- Chat header -->
      <div class="px-6 py-4 border-b border-gray-200">
        <h2 class="text-xl font-semibold text-gray-800">{{ currentChat.title }}</h2>
        <p class="mt-1 text-xs text-gray-500">Recent chat text is sent to Google Gemini. Free-tier data may be used to improve Google's products; avoid sharing sensitive information.</p>
      </div>
      
      <!-- Chat messages - Flex grow to take available space -->
      <div class="flex-1 overflow-y-auto p-6" ref="messagesContainer" style="height: calc(100vh - 180px);">
        <div v-if="loading" class="flex justify-center py-4">
          <div class="animate-spin rounded-full h-8 w-8 border-t-2 border-b-2 border-green-500"></div>
        </div>
        <div v-if="chatLoadError" class="mb-4 text-sm text-red-700" role="alert">
          <p>{{ chatLoadError }}</p>
          <button @click="loadChat(currentChat)" class="mt-2 underline">Try again</button>
        </div>
        
        <div v-for="(message, index) in currentChat.messages" :key="index" class="mb-6">
          <!-- User message -->
          <div v-if="message.role === 'user'" class="flex justify-end">
            <div class="bg-green-100 rounded-lg px-4 py-3 max-w-[75%]">
              <p class="text-gray-800">{{ message.content }}</p>
            </div>
          </div>
          
          <!-- Assistant message -->
          <div v-else class="flex justify-start">
            <div class="bg-gray-100 rounded-lg px-4 py-3 max-w-[75%]">
              <p v-if="isPlaceholderAssistantMessage(message)" class="mb-2 text-xs font-medium text-amber-800">
                Earlier placeholder response — this was not generated by AI.
              </p>
              <div v-if="message.type === 'ingredients'" class="space-y-2">
                <h3 class="font-medium text-gray-800">{{ message.title }}</h3>
                <p class="text-gray-600 text-sm">{{ message.subtitle }}</p>
                
                <div class="mt-4">
                  <div v-for="(item, idx) in message.items" :key="idx" class="flex justify-between py-2 border-b border-gray-200 last:border-0">
                    <span>{{ item.name }}</span>
                    <span class="font-medium">{{ item.quantity }}</span>
                  </div>
                </div>
                
                <div class="mt-4">
                  <h4 class="font-medium">Estimated cost:</h4>
                  <div class="mt-2 space-y-1">
                    <div class="flex items-center">
                      <div class="w-2 h-2 rounded-full bg-green-500 mr-2"></div>
                      <span>Total: {{ message.cost.total }}</span>
                    </div>
                    <div class="flex items-center">
                      <div class="w-2 h-2 rounded-full bg-green-500 mr-2"></div>
                      <span>Per Guest: {{ message.cost.perGuest }}</span>
                    </div>
                  </div>
                  <p class="text-gray-500 text-xs mt-2">{{ message.cost.note }}</p>
                </div>
                
                <!-- Message Actions -->
                <MessageActions 
                  :message="message" 
                  :show-retry="false"
                  @copy="handleCopyMessage"
                  @share="handleShareMessage"
                />
              </div>
              
              <div v-else-if="message.type === 'steps'" class="space-y-4">
                <h3 class="font-medium text-gray-800">{{ message.title }}</h3>
                
                <ol class="list-decimal pl-5 space-y-2">
                  <li v-for="(step, stepIdx) in message.steps" :key="stepIdx" class="text-gray-700">
                    {{ step }}
                  </li>
                </ol>
                
                <!-- Message Actions -->
                <MessageActions 
                  :message="message" 
                  :show-retry="false"
                  @copy="handleCopyMessage"
                  @share="handleShareMessage"
                />
              </div>
              
              <div v-else-if="message.type === 'vendor_offer'" class="space-y-2">
                <div class="flex items-center gap-2">
                  <span class="p-1 bg-green-100 rounded">🛒</span>
                  <h3 class="font-medium">{{ message.title }}</h3>
                </div>
                
                <ul class="mt-2 space-y-1">
                  <li v-for="(point, pointIdx) in message.points" :key="pointIdx" class="flex items-center">
                    <div class="w-2 h-2 rounded-full bg-green-500 mr-2"></div>
                    <span>{{ point }}</span>
                  </li>
                </ul>
                
                <div class="mt-2">
                  <span class="text-sm text-gray-600">Type: </span>
                  <span class="text-sm font-medium">{{ message.actionType }}</span>
                </div>
                
                <!-- Message Actions -->
                <MessageActions 
                  :message="message" 
                  :show-retry="false"
                  @copy="handleCopyMessage"
                  @share="handleShareMessage"
                />
              </div>
              
              <div v-else>
                <p class="text-gray-800">{{ message.content }}</p>
                
                <!-- Message Actions -->
                <MessageActions 
                  :message="message" 
                  :show-retry="false"
                  @copy="handleCopyMessage"
                  @share="handleShareMessage"
                />
              </div>
            </div>
          </div>
        </div>
      </div>
      
      <!-- Message input - Fixed at bottom -->
      <div class="border-t border-gray-200 px-4 py-3 bg-white sticky bottom-0 w-full">
        <div class="relative">
          <input 
            v-model="newMessage" 
            type="text" 
            placeholder="Write a note for your catering plan"
            class="w-full px-4 py-3 pr-12 border border-gray-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-green-500"
            :disabled="sendingMessage"
            @keyup.enter="sendMessage"
          />
          <button 
            @click="sendMessage" 
            :disabled="sendingMessage"
            class="absolute right-2 top-1/2 transform -translate-y-1/2 p-2 bg-green-600 text-white rounded-full hover:bg-green-700"
          >
            <svg class="w-5 h-5" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
              <path d="M5 12H19M19 12L12 5M19 12L12 19" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>
            </svg>
          </button>
        </div>
        <p v-if="sendingMessage" class="mt-2 text-sm text-gray-500" role="status">
          MaaMaa is preparing a reply…
        </p>
        <p class="mt-2 text-sm text-gray-500" role="note">
          Recent chat text is sent to Google Gemini. Free-tier data may be used to improve Google's products.
        </p>
        
        <div class="flex justify-start mt-2">
          <button class="p-2 text-gray-500 hover:text-gray-700">
            <svg class="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 9v3m0 0v3m0-3h3m-3 0H9m12 0a9 9 0 11-18 0 9 9 0 0118 0z" />
            </svg>
          </button>
        </div>
      </div>
    </div>
    
    <!-- Share Modal -->
    <ShareOptions
      :is-open="shareModalOpen"
      :title="currentChat?.title || ''"
      :content="messageToShare"
      @close="shareModalOpen = false"
      @copy-link="handleCopyLink"
      @share-x="handleShareToX"
      @share-linkedin="handleShareToLinkedIn"
    />
    
    <!-- Notification Modal -->
    <div v-if="showNotificationModal" 
         class="fixed top-4 right-4 z-50 w-[calc(100vw-2rem)] max-w-sm">
      <div class="w-full bg-white rounded-lg shadow-lg border-l-4 p-4 transform transition-all"
           :class="{
             'border-green-500': notificationType === 'success',
             'border-red-500': notificationType === 'error',
             'border-blue-500': notificationType === 'info'
           }">
        <div class="flex items-start">
          <!-- Success Icon -->
          <div v-if="notificationType === 'success'" class="flex-shrink-0">
            <svg class="h-5 w-5 text-green-500" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" />
            </svg>
          </div>
          <!-- Error Icon -->
          <div v-if="notificationType === 'error'" class="flex-shrink-0">
            <svg class="h-5 w-5 text-red-500" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 8v4m0 4h.01M21 12a9 9 0 11-18 0 9 9 0 0118 0z" />
            </svg>
          </div>
          
          <div class="ml-3 min-w-0 flex-1">
            <p class="text-sm font-medium break-words"
               :class="{
                 'text-green-800': notificationType === 'success',
                 'text-red-800': notificationType === 'error',
                 'text-blue-800': notificationType === 'info'
               }">
              {{ notificationMessage }}
            </p>
          </div>
          
          <div class="ml-4 flex-shrink-0">
            <button @click="closeNotification" aria-label="Close notification" class="text-gray-400 hover:text-gray-500 focus:outline-none focus:ring-2 focus:ring-green-600 rounded">
              <svg class="h-4 w-4" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M6 18L18 6M6 6l12 12" />
              </svg>
            </button>
          </div>
        </div>
      </div>
    </div>
  </div>
</template>

<script setup>
import { ref, computed, onMounted, watch, inject } from 'vue';
import { useAuthStore } from '~/store/auth';
import MessageActions from '~/components/MessageActions.vue';
import ShareOptions from '~/components/ShareOptions.vue';
import { createChatRepository } from '~/services/chatRepository';

definePageMeta({
  middleware: ['auth'],
  layout: 'chat'
});

const authStore = useAuthStore();
const chatRepository = createChatRepository(useSupabaseClient());
const supabaseClient = useSupabaseClient();
const router = useRouter();
const route = useRoute();

// Get chat data from layout
const chatData = inject('chatData');

// User data
const userName = computed(() => {
  if (authStore.user?.user_metadata?.full_name) {
    return authStore.user.user_metadata.full_name.split(' ')[0];
  }
  return authStore.user?.name?.split(' ')[0] || 'Snow';
});

// Chat state
const loading = ref(false);
const sendingMessage = ref(false);
const pendingNewChat = ref(null);
const newChatMessage = ref('');
const newMessage = ref('');
const messagesContainer = ref(null);

// Share modal state
const shareModalOpen = ref(false);
const messageToShare = ref(null);

// Notification state
const showNotificationModal = ref(false);
const notificationMessage = ref('');
const notificationType = ref('success');

// Use the currentChat from the parent layout if available
const currentChat = ref(null);
const chatLoadError = ref('');

const isPlaceholderAssistantMessage = (message) => {
  if (message.role !== 'assistant') return false;
  return message.content?.startsWith("I've received your message: \"")
    || message.content === "Here's a regenerated response to replace the previous one."
    || message.content?.startsWith("I'll help you with \"");
};

// Load detailed chat data from Supabase
const loadChatMessages = async (chatId) => {
  return chatRepository.listMessages(chatId);
};

// Cache for loaded messages
const chatMessagesCache = ref({});

// Quick suggestions
const suggestions = [
  'Plan an event for me',
  'Help me with my sales breakdown',
  'I need vendors around me'
];

// Methods
const scrollToBottom = () => {
  if (messagesContainer.value) {
    setTimeout(() => {
      messagesContainer.value.scrollTop = messagesContainer.value.scrollHeight;
    }, 100);
  }
};

// Handle message actions
const handleCopyMessage = (message) => {
  navigator.clipboard.writeText(message.content)
    .then(() => {
      // Show success feedback to user
      showNotification('Message copied to clipboard!', 'success');
    })
    .catch(err => {
      showNotification('Failed to copy message. Please try again.', 'error');
    });
};

const handleShareMessage = (message) => {
  messageToShare.value = message;
  shareModalOpen.value = true;
};

// Share modal actions
const handleCopyLink = () => {
  const chatId = currentChat.value.id;
  const url = `${window.location.origin}/chat?id=${chatId}`;
  navigator.clipboard.writeText(url)
    .then(() => {
      shareModalOpen.value = false;
      showNotification('Link copied to clipboard!', 'success');
    })
    .catch(err => {
      showNotification('Failed to copy link. Please try again.', 'error');
    });
};

const handleShareToX = () => {
  const chatId = currentChat.value.id;
  const url = `${window.location.origin}/chat?id=${chatId}`;
  const text = `Check out this conversation about ${currentChat.value.title} on MaaMaa!`;
  const shareUrl = `https://twitter.com/intent/tweet?text=${encodeURIComponent(text)}&url=${encodeURIComponent(url)}`;
  window.open(shareUrl, '_blank', 'noopener,noreferrer');
  shareModalOpen.value = false;
};

const handleShareToLinkedIn = () => {
  const chatId = currentChat.value.id;
  const url = `${window.location.origin}/chat?id=${chatId}`;
  const shareUrl = `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`;
  window.open(shareUrl, '_blank', 'noopener,noreferrer');
  shareModalOpen.value = false;
};

// Add message to chat in database
const addMessageToChat = async (chatId, message) => {
  try {
    await chatRepository.insertMessage(chatId, message);
    return true;
  } catch (error) {
    showNotification('Failed to save message. Please try again.', 'error');
    return false;
  }
};

const generateReply = async (chat) => {
  try {
    const { data: sessionData, error: sessionError } = await supabaseClient.auth.getSession();
    if (sessionError || !sessionData.session?.access_token) throw new Error('AUTH_REQUIRED');

    const messages = (chat.messages || [])
      .filter(message => ['user', 'assistant'].includes(message.role)
        && typeof message.content === 'string'
        && !isPlaceholderAssistantMessage(message))
      .slice(-12)
      .map(({ role, content }) => ({ role, content }));
    const result = await $fetch('/api/ai/chat', {
      method: 'POST',
      headers: { Authorization: `Bearer ${sessionData.session.access_token}` },
      body: { chatId: chat.id, messages },
    });
    if (typeof result.reply !== 'string' || !result.reply.trim()) throw new Error('AI_INVALID_RESPONSE');

    const assistantMessage = { role: 'assistant', content: result.reply.trim(), type: 'text' };
    await chatRepository.insertMessage(chat.id, assistantMessage);
    chat.messages.push(assistantMessage);
    chat.updatedAt = new Date();
    chatMessagesCache.value[chat.id] = chat.messages;
    if (chatData) chatData.updateChatHistory(chat);
    scrollToBottom();
    return true;
  } catch (error) {
    const code = error?.data?.data?.code || error?.data?.code || error?.statusMessage;
    const message = code === 'AI_NOT_CONFIGURED'
      ? 'Your note was saved, but AI is not configured on the server yet.'
      : code === 'AI_RATE_LIMITED'
        ? 'Your note was saved. Please wait a minute before asking MaaMaa again.'
        : 'Your note was saved, but MaaMaa could not generate a reply. Please try again shortly.';
    showNotification(message, 'error');
    return false;
  }
};

const sendMessage = async () => {
  const submittedText = newMessage.value.trim();
  if (!submittedText || !currentChat.value || sendingMessage.value) return;

  const chat = currentChat.value;
  sendingMessage.value = true;
  try {
    // Create user message
    const userMessage = {
      role: 'user',
      content: submittedText
    };
    
    // Add to UI
    if (!currentChat.value.messages) {
      currentChat.value.messages = [];
    }
    chat.messages.push(userMessage);
    
    // Update the chat's timestamp
    chat.updatedAt = new Date();

    // Keep the submitted value independently of the editable input.
    newMessage.value = '';
    scrollToBottom();
    
    // Save message to database
    const saved = await addMessageToChat(chat.id, userMessage);
    if (!saved) {
      const messageIndex = chat.messages.indexOf(userMessage);
      if (messageIndex !== -1) chat.messages.splice(messageIndex, 1);
      if (!newMessage.value) newMessage.value = submittedText;
      return;
    }
    
    // Update chat history in parent layout
    if (chatData) {
      chatData.updateChatHistory(chat);
    }
    await generateReply(chat);
  } finally {
    sendingMessage.value = false;
  }
};

// Create a new chat in the database
const createNewChat = async (title, firstMessage) => {
  let chatData;
  try {
    chatData = await chatRepository.createChat(title, authStore.user.id);
  } catch (error) {
    return { error };
  }

  // Insert first message after the chat exists.
  try {
    await chatRepository.insertMessage(chatData.id, {
      role: 'user',
      content: firstMessage,
    });
  } catch (error) {
    return { error, partialChatId: chatData.id };
  }

  return {
    chat: {
      id: chatData.id,
      title: chatData.title,
      updatedAt: new Date(chatData.updated_at),
      messages: [
        {
          role: 'user',
          content: firstMessage
        }
      ]
    }
  }
};

const sendNewMessage = async () => {
  const submittedText = newChatMessage.value.trim();
  if (!submittedText || sendingMessage.value) return;

  sendingMessage.value = true;
  try {
    let newChat;
    if (pendingNewChat.value) {
      const pending = pendingNewChat.value;
      const userMessage = { role: 'user', content: submittedText };
      const saved = await addMessageToChat(pending.id, userMessage);
      if (!saved) {
        showNotification('This chat exists, but its note is still not saved. Retry to use the same chat.', 'error');
        return;
      }
      newChat = {
        id: pending.id,
        title: pending.title,
        updatedAt: new Date(),
        messages: [userMessage]
      };
      pendingNewChat.value = null;
    } else {
      const result = await createNewChat(submittedText, submittedText);
      if (result.partialChatId) {
        pendingNewChat.value = { id: result.partialChatId, title: submittedText };
        showNotification('The chat was created, but the note was not saved. Retry to save it in this chat without creating another.', 'error');
        return;
      }
      newChat = result.chat;
    }

    if (!newChat) {
      showNotification('Your note could not be saved. Please try again.', 'error');
      return;
    }

    currentChat.value = newChat;
    if (chatData) {
      chatData.updateChatHistory(newChat);
      chatData.currentChatId = newChat.id;
    }

    router.replace({ path: '/chat', query: { id: newChat.id } });
    if (newChatMessage.value.trim() === submittedText) newChatMessage.value = '';
    await generateReply(newChat);
  } finally {
    sendingMessage.value = false;
  }
};

const startChatWithSuggestion = (suggestion) => {
  newChatMessage.value = suggestion;
  sendNewMessage();
};

const loadChat = async (chat) => {
  chatLoadError.value = '';
  // If we already have messages loaded for this chat, use them
  if (chatMessagesCache.value[chat.id]) {
    currentChat.value = {
      ...chat,
      messages: chatMessagesCache.value[chat.id]
    };
    scrollToBottom();
    return;
  }
  
  // Otherwise, load messages from the database
  loading.value = true;
  try {
    const messages = await loadChatMessages(chat.id);
    
    // Update the current chat with messages
    currentChat.value = {
      ...chat,
      messages
    };
    
    // Cache the messages
    chatMessagesCache.value[chat.id] = messages;
    
    loading.value = false;
    scrollToBottom();
  } catch (error) {
    loading.value = false;
    chatLoadError.value = 'This chat could not be loaded. Check your connection and try again.';
    
    // Set empty messages array if there was an error
    currentChat.value = {
      ...chat,
      messages: []
    };
  }
};

// Function to load chat from URL query parameters
const loadChatFromUrlParams = async () => {
  const chatId = route.query.id;
  
  if (!chatId) {
    // No chat ID in URL, show welcome screen
    currentChat.value = null;
    chatLoadError.value = '';
    return;
  }
  
  // Check if the chat is in the history
  if (chatData) {
    const chat = chatData.chatHistory.find(c => c.id === chatId);
    if (chat) {
      await loadChat(chat);
      return;
    }
  }
  
  // If we get here, try to fetch the chat directly from the database
  try {
    const chat = await chatRepository.getChat(String(chatId));
    
    if (chat) {
      // Format the chat data
      const formattedChat = {
        id: chat.id,
        title: chat.title,
        updatedAt: new Date(chat.updated_at)
      };
      
      // Load messages for this chat
      await loadChat(formattedChat);
      
      // Update chat history in parent layout
      if (chatData) {
        chatData.currentChatId = chatId;
        chatData.updateChatHistory(currentChat.value);
      }
    } else {
      // Chat not found
      currentChat.value = null;
      router.replace('/chat');
    }
  } catch (error) {
    currentChat.value = null;
    router.replace('/chat');
  }
};

// Watch for changes in route query parameters
watch(() => route.query.id, async (newChatId, oldChatId) => {
  // Only reload if the ID actually changed
  if (newChatId !== oldChatId) {
    await loadChatFromUrlParams();
  }
}, { immediate: true });

// Register this component with the layout
onMounted(async () => {
  if (chatData) {
    // Register this component with the layout
    chatData.setChatPageInstance({
      loadChat,
      currentChat,
      resetChat: () => {
        currentChat.value = null;
      }
    });
    
    // Load chat based on URL parameters
    await loadChatFromUrlParams();
  }
  
  // Scroll to bottom of messages if any
  scrollToBottom();
});

// Watch for changes to current chat to scroll to bottom
watch(() => currentChat.value?.messages?.length, () => {
  scrollToBottom();
});

// Notification functions
const showNotification = (message, type = 'success') => {
  notificationMessage.value = message;
  notificationType.value = type;
  showNotificationModal.value = true;
  
  // Auto-hide notification after 3 seconds for success messages
  if (type === 'success') {
    setTimeout(() => {
      showNotificationModal.value = false;
    }, 3000);
  }
};

const closeNotification = () => {
  showNotificationModal.value = false;
};
</script>
